"""
Code Generation Tool.

A meta-tool that uses an LLM to generate Python code that composes
other Friday tools to accomplish complex tasks.

Ref: Code Generation Tool specification
"""

from __future__ import annotations

import re
from typing import Any, TYPE_CHECKING

from ..definition import BaseTool
from ..manifest import ToolManifest
from .prompts import SYSTEM_PROMPT, build_user_prompt

if TYPE_CHECKING:
    from friday_core.interfaces.llm import LLMClient


class CodeGenerationTool(BaseTool):
    """
    Generate and execute Python code using available Friday tools.

    This meta-tool:
    1. Receives a task description from the agent
    2. Consults the tool manifest to see available tools
    3. Uses an LLM to generate Python code that uses those tools
    4. Executes the generated code unsandboxed
    5. Returns the result

    Example:
        from friday_tools import ToolManifest, get_default_registry
        from friday_tools.codegen import CodeGenerationTool

        registry = get_default_registry()
        manifest = ToolManifest(registry)
        code_gen = CodeGenerationTool(llm=my_llm_client, manifest=manifest)

        result = await code_gen.execute(
            task="Read config.json and extract the 'version' field"
        )
    """

    def __init__(
        self,
        llm: "LLMClient",
        manifest: ToolManifest,
        temperature: float = 0.2,
    ):
        """
        Initialize the code generation tool.

        Args:
            llm: LLM client for generating code (injected from agent)
            manifest: Tool manifest describing available tools
            temperature: LLM temperature for code generation (lower = more deterministic)
        """
        self._llm = llm
        self._manifest = manifest
        self._temperature = temperature

    @property
    def name(self) -> str:
        return "code_generate"

    @property
    def description(self) -> str:
        return (
            "Generate and execute Python code to accomplish a task using "
            "available Friday tools. The code is generated by an LLM based "
            "on the task description and available tools, then executed. "
            "Use this for complex tasks that require composing multiple tools "
            "or custom logic."
        )

    @property
    def parameters_schema(self) -> dict[str, Any]:
        return {
            "type": "object",
            "properties": {
                "task": {
                    "type": "string",
                    "description": (
                        "Description of what the code should accomplish. "
                        "Be specific about inputs, outputs, and any constraints."
                    ),
                },
                "context": {
                    "type": "string",
                    "description": (
                        "Additional context, constraints, or hints for code generation. "
                        "For example: file paths, expected data formats, error handling preferences."
                    ),
                    "default": "",
                },
            },
            "required": ["task"],
        }

    async def execute(self, **kwargs: Any) -> str:
        """
        Generate and execute code for the given task.

        Args:
            task: Description of what to accomplish
            context: Additional context or constraints

        Returns:
            String containing the generated code and execution result
        """
        task = kwargs["task"]
        context = kwargs.get("context", "")

        # 1. Build prompt with tool manifest
        tool_context = self._manifest.to_prompt_context()
        user_prompt = build_user_prompt(task, context, tool_context)

        # 2. Call LLM to generate code
        response = await self._llm.chat_completion(
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            temperature=self._temperature,
        )

        if response.content is None:
            return "Error: LLM returned no content"

        # 3. Extract code from response
        code = self._extract_code(response.content)
        if not code:
            return f"Error: Could not extract code from LLM response:\n{response.content}"

        # 4. Execute the code unsandboxed (needs access to friday_tools)
        from ..execution import python_execute_unsandboxed

        result = await python_execute_unsandboxed.execute(code=code)

        # 5. Format and return result
        return self._format_result(code, result)

    def _extract_code(self, content: str) -> str | None:
        """
        Extract Python code from LLM response.

        Looks for code blocks in markdown format:
        ```python
        code here
        ```

        Args:
            content: Raw LLM response

        Returns:
            Extracted code or None if not found
        """
        # Try to find python code block
        pattern = r"```python\s*\n(.*?)```"
        match = re.search(pattern, content, re.DOTALL)
        if match:
            return match.group(1).strip()

        # Try generic code block
        pattern = r"```\s*\n(.*?)```"
        match = re.search(pattern, content, re.DOTALL)
        if match:
            return match.group(1).strip()

        # If no code block, check if entire response looks like code
        if content.strip().startswith(("import ", "from ", "async ", "def ", "#")):
            return content.strip()

        return None

    def _format_result(self, code: str, execution_result: str) -> str:
        """
        Format the code and result for return.

        Args:
            code: The generated Python code
            execution_result: Output from code execution

        Returns:
            Formatted string with code and result
        """
        return (
            f"## Generated Code\n\n"
            f"```python\n{code}\n```\n\n"
            f"## Execution Result\n\n{execution_result}"
        )

    @property
    def manifest(self) -> ToolManifest:
        """Access the tool manifest."""
        return self._manifest

    def list_available_tools(self) -> list[str]:
        """Get list of tools available for code generation."""
        return self._manifest.list_tool_names()
