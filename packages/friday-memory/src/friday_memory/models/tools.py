"""
Tool-related models for friday-memory.

Defines data models for tool usage tracking, recommendations, and context
integration. These models support the intelligent tool selection system.

Ref: Tool Calling Build Plan - Phase 1
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_serializer


class ToolUsageRecord(BaseModel):
    """
    Record of a single tool invocation for learning and analytics.

    Captures details about tool usage to enable:
    - Learning which tools are effective for which queries
    - Recommending tools based on historical success
    - Tracking tool performance and errors
    """

    model_config = ConfigDict(arbitrary_types_allowed=True)

    id: str = Field(description="Unique identifier for this usage record")
    tool_name: str = Field(description="Name of the tool that was invoked")
    tool_category: str = Field(
        default="uncategorized",
        description="Category of the tool (filesystem, web, shell, etc.)",
    )
    session_id: str = Field(description="Session in which the tool was used")
    turn_id: str = Field(description="Turn within the session")
    query_context: str = Field(
        description="User query or context that triggered the tool use"
    )
    parameters: dict[str, Any] = Field(
        default_factory=dict,
        description="Parameters passed to the tool",
    )
    success: bool = Field(description="Whether the tool execution succeeded")
    error_type: str | None = Field(
        default=None,
        description="Type of error if execution failed",
    )
    error_message: str | None = Field(
        default=None,
        description="Error message if execution failed",
    )
    latency_ms: float = Field(
        default=0.0,
        description="Execution time in milliseconds",
    )
    result_size: int = Field(
        default=0,
        description="Size of result in characters (for analytics)",
    )
    timestamp: datetime = Field(
        default_factory=datetime.now,
        description="When the tool was invoked",
    )

    @field_serializer("timestamp")
    def serialize_timestamp(self, timestamp: datetime) -> str:
        """Serialize datetime to ISO format."""
        return timestamp.isoformat()


class ToolRecommendation(BaseModel):
    """
    Recommendation for tool use in the current context.

    Generated by the ToolContextManager based on query analysis,
    historical usage patterns, and tool capabilities.
    """

    tool_name: str = Field(description="Name of the recommended tool")
    category: str = Field(
        default="uncategorized",
        description="Category of the recommended tool",
    )
    relevance_score: float = Field(
        ge=0.0,
        le=1.0,
        description="Relevance score from 0.0 to 1.0",
    )
    reason: str = Field(
        description="Human-readable explanation of why this tool is recommended"
    )
    suggested_parameters: dict[str, Any] | None = Field(
        default=None,
        description="Suggested parameter values based on context",
    )
    confidence: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
        description="Confidence in this recommendation (0.0 to 1.0)",
    )

    def to_hint(self) -> str:
        """
        Convert recommendation to a natural language hint for context.

        Returns:
            String suitable for inclusion in supporting context.
        """
        hint = f"- {self.tool_name}: {self.reason}"
        if self.suggested_parameters:
            params = ", ".join(f"{k}={v}" for k, v in self.suggested_parameters.items())
            hint += f" (suggested: {params})"
        return hint


class ToolSchema(BaseModel):
    """
    Lightweight representation of a tool schema for context payload.

    This is a simplified view of a tool for inclusion in context,
    containing only the essential information needed for LLM tool calling.
    """

    name: str = Field(description="Tool name")
    description: str = Field(description="Tool description")
    category: str = Field(default="uncategorized", description="Tool category")
    parameters: dict[str, Any] = Field(
        default_factory=dict,
        description="JSON Schema for parameters",
    )
    tags: list[str] = Field(
        default_factory=list,
        description="Tool tags for filtering",
    )

    def to_openai_schema(self) -> dict[str, Any]:
        """
        Convert to OpenAI function calling format.

        Returns:
            Dictionary in OpenAI tool schema format.
        """
        return {
            "type": "function",
            "function": {
                "name": self.name,
                "description": self.description,
                "parameters": self.parameters,
            },
        }

    def to_plain_schema(self) -> dict[str, Any]:
        """
        Convert to plain schema format.

        Returns:
            Dictionary with name, description, parameters, category, tags.
        """
        return {
            "name": self.name,
            "description": self.description,
            "parameters": self.parameters,
            "category": self.category,
            "tags": self.tags,
        }
